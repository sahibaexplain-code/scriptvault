/**
 * Generates supabase/seed.sql from the sample catalogue.
 * Usage: npm run seed:sql
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { BUNDLES, CATEGORIES, SCRIPTS } from "../src/lib/catalog/sample-data";

// sample-bodies.ts starts with `import "server-only"`, which throws outside Next.
// Read it as text and evaluate the object literal instead.
import { readFileSync } from "node:fs";
const src = readFileSync(join(__dirname, "../src/lib/catalog/sample-bodies.ts"), "utf8");
const objText = src.slice(src.indexOf("{", src.indexOf("SAMPLE_BODIES")), src.lastIndexOf("}") + 1);
const SAMPLE_BODIES: Record<string, string> = new Function(`return (${objText});`)();

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `array[${v.map(q).join(", ")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const out: string[] = [
  "-- Generated by `npm run seed:sql`. Safe to re-run: existing rows are updated.",
  "begin;",
];

CATEGORIES.forEach((c, i) =>
  out.push(`insert into public.categories (slug, name, sort_order) values (${q(c.slug)}, ${q(c.name)}, ${i}) on conflict (slug) do update set name = excluded.name, sort_order = excluded.sort_order;`)
);

for (const s of SCRIPTS) {
  out.push(`insert into public.scripts (id, slug, title, subtitle, category_slug, language, format, duration_minutes, word_count, price_inr, exclusive_price_inr, exclusive_available, description, preview, tags, is_featured, is_published, sales_count, rating, created_at)
values (${[s.id, s.slug, s.title, s.subtitle, s.category, s.language, s.format, s.durationMinutes, s.wordCount, s.priceInr, s.exclusivePriceInr, s.exclusiveAvailable, s.description, s.preview, s.tags, s.isFeatured, s.isPublished, s.salesCount, s.rating, s.createdAt].map(q).join(", ")})
on conflict (id) do update set title = excluded.title, subtitle = excluded.subtitle, description = excluded.description, preview = excluded.preview, price_inr = excluded.price_inr, exclusive_price_inr = excluded.exclusive_price_inr, tags = excluded.tags;`);
  const body = `${s.preview}\n\n${SAMPLE_BODIES[s.slug] ?? ""}`.trim();
  out.push(`insert into public.script_contents (script_id, body) values (${q(s.id)}, ${q(body)}) on conflict (script_id) do update set body = excluded.body;`);
}

for (const b of BUNDLES) {
  out.push(`insert into public.bundles (id, slug, title, description, price_inr, badge, is_published) values (${[b.id, b.slug, b.title, b.description, b.priceInr, b.badge, b.isPublished].map(q).join(", ")}) on conflict (id) do update set title = excluded.title, description = excluded.description, price_inr = excluded.price_inr, badge = excluded.badge;`);
  for (const sid of b.scriptIds) out.push(`insert into public.bundle_items (bundle_id, script_id) values (${q(b.id)}, ${q(sid)}) on conflict do nothing;`);
}

out.push("commit;", "");
writeFileSync(join(__dirname, "../supabase/seed.sql"), out.join("\n"));
console.log(`Wrote supabase/seed.sql (${SCRIPTS.length} scripts, ${BUNDLES.length} bundles)`);
